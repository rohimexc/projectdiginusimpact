// belajar tipe Data

// tipe data string
let data = "apri";
console.log(data);
console.log(typeof data); // berguna untuk mengetahui tipe data dari variable

// tipe data number
let data2 = 20;
console.log(data2);
console.log(typeof data2);

// tipe data boolean
// tipe data boolean hanya memiliki 2 nilai yaitu true dan false
let data3 = true;
console.log(data3);
console.log(typeof data3);  

// kita bisa mengubah tipe data dari variable, misalnya dari string menjadi number, atau sebaliknya
datastring = 20;
console.log(datastring);
console.log(typeof datastring); // berguna untuk mengetahui tipe data dari variable


// tipe data undefined
// tipe data undefined adalah tipe data yang belum memiliki nilai, atau belum di definisikan
let data4;
console.log(data4);
console.log(typeof data4); // berguna untuk mengetahui tipe data dari variable
// sama seperti yang di atas, kita bisa mengubah tipe data dari variable, misalnya dari undefined menjadi string, atau sebaliknya
data4 = "apri";
console.log(data4);
console.log(typeof data4); // berguna untuk mengetahui tipe data dari variable